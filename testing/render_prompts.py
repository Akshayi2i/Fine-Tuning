"""Generate ``testing/prompts/*.prompt.txt`` from ``common.prompts`` (IMPL-12 §2).

One file per active doc type, carrying the role framing, the injected JSON schema
pulled from the IMPL-01 registry, the extraction rules, and the modality-mode
line. Separate files because each type has a different schema and different field
semantics — a Loss Run's valuation date is not an ACORD's policy effective date —
so one type's prompt can be tuned without risk to the others.

**These are generated, never hand-edited.** The spec's requirement is that they
resolve to the identical rendered prompt as ``common.prompts``, asserted in a
test rather than maintained by discipline. Two hand-kept copies of a prompt
diverge by one character eventually, and prompt drift between training and
inference is the most common cause of post-fine-tuning degradation — invisible in
every training metric.

So: this module writes them, and ``test_prompt_files_match_the_renderer`` fails
the moment a checked-in file stops matching a fresh render. Regenerate with::

    python -m testing.render_prompts --write
"""

from __future__ import annotations

import argparse
import logging
from collections.abc import Iterable
from pathlib import Path

from common.constants import ACORD_FORMS, ACTIVE_DOC_TYPES
from common.prompts import (
    GROUP_BLOCK_SEPARATOR,
    PROMPT_TEMPLATE_VERSION,
    render_group_block,
    render_system_prompt,
)
from common.schemas import SNAPSHOT_LINES

log = logging.getLogger(__name__)

PROMPTS_DIR = Path(__file__).resolve().parent / "prompts"

#: The mode these reference files render. ``ocr_plus_image`` is the primary
#: production mode, and ``noisy_ocr_image`` renders identically to it by design,
#: so one file covers both; the image-only variant differs and is emitted too.
REFERENCE_MODES: tuple[str, ...] = ("ocr_plus_image", "image_only")

def reference_targets() -> list[tuple[str, str | None, str | None]]:
    """Every ``(doc_type, acord_form, lob)`` triple that renders a distinct prompt.

    ACORD gets one file **per form**, not one for the type: 25, 125 and 140 have
    different schemas, so a single acord file pinned to one of them would be a
    reference that misrepresents the other two.

    Policies get one **per registered line of business**, for the same reason and
    with more at stake: a homeowners prompt and an ocean marine prompt carry
    different canonical schemas, and the generic `policy` file proves nothing
    about either. The bare `policy` entry stays — it is what a package policy and
    an unclassified line still render.
    """
    targets: list[tuple[str, str | None, str | None]] = []
    for doc_type in ACTIVE_DOC_TYPES:
        if doc_type == "acord":
            targets += [(doc_type, form, None) for form in sorted(ACORD_FORMS, key=int)]
            continue
        targets.append((doc_type, None, None))
        if doc_type == "policy":
            targets += [(doc_type, None, lob) for lob in SNAPSHOT_LINES]
    return targets


def window_targets() -> list[tuple[str, str]]:
    """Every ``(lob, group)`` window prompt of a common-model line: what training
    rows and serving actually send - a section group's slice of the schema, its
    outline and its rules - where the files above show the whole schema. In the
    primary mode only: the image-only text differs from it in the evidence
    paragraph alone, which the whole-schema image-only file shows."""
    from common.schema_sections import groups_for
    from common.schemas import is_common_model

    return [(lob, group) for lob in SNAPSHOT_LINES
            if is_common_model("policy", None, lob) for group in groups_for(lob)]


def _reference_files() -> list[tuple[str, str, str | None, str | None, str | None]]:
    """``(doc_type, mode, acord_form, lob, sections)`` of every reference file."""
    files = [(doc_type, mode, form, lob, None)
             for doc_type, form, lob in reference_targets() for mode in REFERENCE_MODES]
    files += [("policy", REFERENCE_MODES[0], None, lob, group) for lob, group in window_targets()]
    return files


def stem(doc_type: str, acord_form: str | None, lob: str | None = None, sections: str | None = None) -> str:
    if acord_form:
        return f"{doc_type}_{acord_form}"
    base = f"{doc_type}_{lob}" if lob else doc_type
    return f"{base}.{sections}" if sections else base


def header(doc_type: str, modality_mode: str) -> str:
    """A provenance banner, kept out of the compared body.

    The banner records what produced the file and at which template version, so
    a stale file is identifiable on sight rather than only when a test fails.
    """
    return (
        f"# GENERATED by testing.render_prompts — do not edit.\n"
        f"# doc_type={doc_type} modality_mode={modality_mode} "
        f"prompt_template_version={PROMPT_TEMPLATE_VERSION}\n"
        f"# Regenerate: python -m testing.render_prompts --write\n"
    )


def prompt_path(
    doc_type: str,
    modality_mode: str,
    acord_form: str | None = None,
    root: Path = PROMPTS_DIR,
    lob: str | None = None,
    sections: str | None = None,
) -> Path:
    suffix = "" if modality_mode == "ocr_plus_image" else f".{modality_mode}"
    return root / f"{stem(doc_type, acord_form, lob, sections)}{suffix}.prompt.txt"


#: Stands for the window's pages between the system prompt and the group's
#: request in a fast-format reference file: the pages are the document's, not
#: the prompt's.
PAGES_MARK = ("\n\n# ---- user turn: the window's pages (each image, then `<page N of M>` and its text), "
              "then the request ----")


def render(
    doc_type: str, modality_mode: str, acord_form: str | None = None, lob: str | None = None,
    sections: str | None = None,
) -> str:
    """The prompt body exactly as ``common.prompts`` renders it: the system
    prompt, and under the fast format profile (configs/shared/format.yaml) the
    group's own request, which the model reads after the window's pages."""
    system = render_system_prompt(doc_type, modality_mode, acord_form=acord_form, lob=lob, sections=sections)
    block = render_group_block(doc_type, acord_form, lob, sections) if sections else None
    if block is None:
        return system
    return system + PAGES_MARK + GROUP_BLOCK_SEPARATOR + block


def file_contents(
    doc_type: str, modality_mode: str, acord_form: str | None = None, lob: str | None = None,
    sections: str | None = None,
) -> str:
    return (
        header(stem(doc_type, acord_form, lob, sections), modality_mode)
        + "\n"
        + render(doc_type, modality_mode, acord_form, lob, sections)
    )


def body_of(text: str) -> str:
    """Strip the generated banner, leaving the prompt to compare."""
    lines = text.splitlines(keepends=True)
    while lines and lines[0].startswith("#"):
        lines.pop(0)
    if lines and not lines[0].strip():
        lines.pop(0)
    return "".join(lines)


def write_all(root: Path = PROMPTS_DIR) -> list[Path]:
    """Regenerate every reference prompt file."""
    root.mkdir(parents=True, exist_ok=True)
    written = []
    for doc_type, mode, form, lob, sections in _reference_files():
        path = prompt_path(doc_type, mode, form, root, lob, sections)
        path.write_text(file_contents(doc_type, mode, form, lob, sections), encoding="utf-8")
        written.append(path)

    # A file left over from a renamed target is a reference nothing regenerates,
    # and the drift check would never look at it.
    expected = {p.name for p in written}
    for stale in sorted(root.glob("*.prompt.txt")):
        if stale.name not in expected:
            stale.unlink()
            log.warning("removed stale reference prompt %s", stale.name)

    log.info("wrote %d reference prompt file(s) to %s", len(written), root)
    return written


def drifted(root: Path = PROMPTS_DIR) -> list[str]:
    """Files whose body no longer matches a fresh render.

    A missing file counts as drift: an absent reference cannot prove anything,
    and treating it as passing would defeat the check.
    """
    problems = []
    expected: set[str] = set()
    for doc_type, mode, form, lob, sections in _reference_files():
        path = prompt_path(doc_type, mode, form, root, lob, sections)
        expected.add(path.name)
        if not path.exists():
            problems.append(f"{path.name}: missing")
            continue
        if body_of(path.read_text(encoding="utf-8")) != render(doc_type, mode, form, lob, sections):
            problems.append(f"{path.name}: differs from common.prompts")

    problems += [
        f"{path.name}: stale, nothing regenerates it"
        for path in sorted(root.glob("*.prompt.txt"))
        if path.name not in expected
    ]
    return problems


#: Fingerprints of every selector that is not a common-model line, frozen when
#: the SPEC_21 schemas arrived. The common-model work changes code every one of
#: those selectors runs through - the registry, the model view, the templates,
#: the section map - and none of it may change what they render.
FINGERPRINTS_PATH = (
    Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "old_style_prompt_fingerprints.json"
)


def old_style_fingerprints() -> dict[str, dict[str, str]]:
    """SHA-256 of the prompt, the decoding schema and the required fields, per selector.

    Every registered selector except the common-model lines, over the whole
    schema and every window slice, in both reference modes. The snapshots in
    ``testing/prompts`` cover only the personal-lines family and the whole
    schema; this covers the rest, including the windowed prompts serving sends.
    """
    import hashlib
    import json

    from common.schema_sections import groups_for
    from common.schemas import is_common_model, required_fields, resolved_schema, schema_selectors

    def sha(text: str) -> str:
        return hashlib.sha256(text.encode("utf-8")).hexdigest()

    out: dict[str, dict[str, str]] = {}
    for doc_type, form, lob in schema_selectors():
        if doc_type == "policy" and is_common_model(doc_type, form, lob):
            continue
        slices: list[str | None] = [None]
        if doc_type == "policy":
            slices += list(groups_for(lob))
        for sections in slices:
            entry = {
                "schema": sha(json.dumps(
                    resolved_schema(doc_type, form, lob, sections), sort_keys=True, ensure_ascii=False
                )),
                "required": sha(json.dumps(required_fields(doc_type, form, lob, sections))),
            }
            for mode in REFERENCE_MODES:
                entry[f"prompt.{mode}"] = sha(
                    render_system_prompt(doc_type, mode, form, lob, sections)
                )
            out[f"{stem(doc_type, form, lob)}#{sections or 'whole'}"] = entry
    return out


def write_fingerprints(path: Path = FINGERPRINTS_PATH) -> Path:
    """Re-freeze the fingerprints, rendered in the standard format profile: the one
    tests/test_old_style_prompts_frozen.py compares them in, whatever profile
    configs/shared/format.yaml ships (the fast one writes a policy window another way)."""
    import json

    import common.config

    shipped = common.config.shared_format_config
    common.config.shared_format_config = lambda: {"profile": "standard"}
    try:
        fingerprints = old_style_fingerprints()
    finally:
        common.config.shared_format_config = shipped
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(fingerprints, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    return path


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render the reference prompt files")
    parser.add_argument("--write", action="store_true", help="regenerate the files")
    parser.add_argument(
        "--write-fingerprints", action="store_true",
        help="re-freeze the old-style fingerprints (only for a deliberate change to those lines)",
    )
    parser.add_argument("--root", type=Path, default=PROMPTS_DIR)
    args = parser.parse_args(list(argv) if argv is not None else None)

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    if args.write_fingerprints:
        print(write_fingerprints())
        return 0
    if args.write:
        for path in write_all(args.root):
            print(path)
        return 0

    problems = drifted(args.root)
    for problem in problems:
        print(problem)
    if problems:
        print("run with --write to regenerate")
    return 1 if problems else 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
