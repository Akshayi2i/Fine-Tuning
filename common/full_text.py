"""The full-text tier, ``text_sections``: every printed word, organised by form and section.

Built from the page text a request already carries, by Fideon's deterministic
section builder (:mod:`common.section_builder`, a copy of FideonSLM's) - never by
the model. Fideon SPEC_21 §4.6 marks the tier ``fideon:fsm_exclude``, "assembled
from MinerU output by the section builder, not generated by the model", and
SPEC_09 has it "excluded from every assistant target; it is attached at inference
by the section builder". So no training row teaches it, no window asks for it,
and it costs no generation.

With the fields and ``additional_fields`` it is what puts every printed word
somewhere in the served JSON - SPEC_21's every-word rule, its check C4.
:func:`text_coverage` measures that rule on each served document.
"""

from __future__ import annotations

from collections.abc import Iterator, Sequence
from typing import Any


def build_text_sections(page_texts: Sequence[str | None]) -> dict[str, dict[str, Any]]:
    """``text_sections`` from one MinerU markdown string per page, in page order.

    ``{}`` when no page has text - an image-only request carries none, and there
    is nothing to section. The keys are the builder's stable section keys
    (``<form number or NOFORM>|<top heading>|<sub-path>``).
    """
    from common.section_builder.sections import build, pages_from_markdown

    texts = [text or "" for text in page_texts]
    if not any(text.strip() for text in texts):
        return {}
    pages = pages_from_markdown(texts)
    _anchor_tables(pages)
    return build(pages)


def _anchor_tables(pages: list[Any]) -> None:
    """Give every markdown table a line inside its box, so ``build`` writes it.

    FideonSLM's builder (as copied, 3d40d77) writes a table out when a line of
    the page falls inside the table's box - true of a digital PDF, whose table
    text is also its lines. ``pages_from_markdown`` keeps a table's rows out of
    the page's lines, so no line is ever inside one and every MinerU table was
    dropped: a declarations page's coverage schedule was in no part of the JSON.
    Fixed here, not in the copy, which stays FideonSLM's byte for byte; to be
    fixed there (the same loss reaches L1 on MinerU text).

    The anchor is never written: a line inside a table only triggers the table.
    Its text holds a ``#``, so it is never a form title; letters number it, so it
    is never a header repeated across pages; and it names no form or value.
    """
    from common.section_builder.sections import L

    for page in pages:
        for index, table in enumerate(page.tables):
            x0, y0, x1, _y1 = table.bbox
            anchor = f"#table-anchor-{_letters(page.page)}-{_letters(index)}"
            page.lines.append(L(anchor, (x0, y0, x1, y0 + 2), 10.0, False))


def _letters(number: int) -> str:
    """``number`` in letters (0 -> a, 25 -> z, 26 -> ba): no digit to normalise
    away when the builder compares lines across pages."""
    out = ""
    while True:
        number, digit = divmod(number, 26)
        out = chr(ord("a") + digit) + out
        if not number:
            return out


def text_coverage(page_texts: Sequence[str | None], output: Any) -> float | None:
    """The share of the page text's words found anywhere in ``output``.

    Counted as SPEC_21's check C4 counts them (the builder's own ``coverage``):
    words with their repeats, in any order, against every string value of the
    served JSON - fields, ``additional_fields`` and ``text_sections`` alike; never
    its keys. ``None`` when no page has text: an image-only request is measured
    by nothing here, not counted as complete.

    Measured against the page text the request carried, so it says whether
    anything read was left out of the JSON - not what the OCR itself missed on a
    scan.
    """
    from common.section_builder.sections import coverage, words

    page_words = [word for text in page_texts for word in words(text or "")]
    if not page_words:
        return None
    return round(coverage(page_words, " ".join(_strings(output))), 4)


def _strings(node: Any) -> Iterator[str]:
    """Every string value under ``node``, depth first; numbers as written."""
    if isinstance(node, str):
        yield node
    elif isinstance(node, bool) or node is None:
        return
    elif isinstance(node, int | float):
        yield str(node)
    elif isinstance(node, dict):
        for value in node.values():
            yield from _strings(value)
    elif isinstance(node, list):
        for value in node:
            yield from _strings(value)
